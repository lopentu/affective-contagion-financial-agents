"""Generate one roster per model in the PR2 comparison ladder.

Every roster must differ *only* in the checkpoint. Role prompts, decoding, temperature, dtype and
the constrained flag are held identical, so that a difference in outcome can be attributed to the
model. Generating the rosters makes that checkable, and `tests/test_ladder_rosters.py` asserts one
distinct body once the model block is removed.

Revisions are pinned as literal commit hashes. Re-resolving them from the Hub could silently change
which weights a model key names.
"""

