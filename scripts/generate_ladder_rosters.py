# Held identical across every rung. Any change here applies to all eight at once.
AGENTS = """agents:
- role: sentiment_analyst
  model_key: {key}
  system_prompt: Assess market mood while distinguishing rhetoric from financial evidence.
- role: fundamental_analyst
  model_key: {key}
  system_prompt: Focus on reported evidence, valuation, and fair value.
- role: bull_researcher
  model_key: {key}
  system_prompt: Identify honest upside evidence and counterarguments.
- role: bear_researcher
  model_key: {key}
  system_prompt: Identify honest downside evidence and counterarguments.
- role: trader
  model_key: {key}
  system_prompt: Use the team's evidence to choose a bounded trade.
- role: risk_manager
  model_key: {key}
  system_prompt: Evaluate exposure and tail risk without confusing rhetoric with probability.
"""

TEMPLATE = """# {note}
# Generated by scripts/generate_ladder_rosters.py. Do not hand-edit. Every field except the model
# block must stay identical across the whole ladder, or a difference in outcome cannot be attributed
# to the model.
schema_version: 1
models:
- key: {key}
  repository: {repository}
  revision: {revision}
  activation_layer: null
  dtype: bfloat16
  device_map: auto
  quantization: none
  max_new_tokens: 256
  temperature: 0.7
  constrained_decision_format: true
{agents}"""


def main() -> None:
    """Write one roster per rung, overwriting any previous generation."""
    destination = Path("configs/models/ladder")
    destination.mkdir(parents=True, exist_ok=True)
    for rung in LADDER:
        (destination / f"{rung.filename}.yaml").write_text(
            TEMPLATE.format(
                note=rung.note,
                key=rung.key,
                repository=rung.repository,
                revision=rung.revision,
                agents=AGENTS.format(key=rung.key),
            ),
            encoding="utf-8",
        )
    print(f"wrote {len(LADDER)} ladder rosters to {destination}")


if __name__ == "__main__":
    main()
