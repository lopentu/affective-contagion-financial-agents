"""Write the run configs PR5 specifies, so the seed and role assignment is code rather than typing.

PR5 needs 4 scenarios x 36 seeds x 2 arms = 288 runs. The treated role is balanced: each of the
six roles is the sender for exactly 6 of the 36 seeds in every scenario, assigned by seed order
rather than at random, so the mapping is reproducible and auditable from this file alone.
"""

from __future__ import annotations

import pathlib

from affective_contagion.config import DEFAULT_ROLES

SEEDS = range(300, 336)  # 36 seeds, disjoint from every other design's seed block
ARMS = {"neutral": "neutral", "affective": "affective"}
OUTPUT = pathlib.Path("configs/experiments/pr5")

TEMPLATE = """# Generated by scripts/generate_pr5_configs.py. Do not hand-edit.
# PR5: one-round transmission. The treated agent's delivered message is replaced after it has
# decided and traded, so the two arms differ in exactly one delivered message at the treatment
# round. The agent reads its arm's rendering before deciding, so its trade and the next-round
# price are not held fixed.
roles:
  - sentiment_analyst
  - fundamental_analyst
  - bull_researcher
  - bear_researcher
  - trader
  - risk_manager
topology: full
n_rounds: 12
shock_round: 8
shock_duration: 1
treated_role: {role}
shock_type: {arm}
message_intervention: inject_message
fundamental_value: 100.0
price_impact: 0.02
mean_reversion: 0.01
noise_sigma: 0.003
seed: {seed}
var_maxlags: 3
irf_horizon: 10
"""


def main() -> None:
    """Write one config per (seed, arm)."""
    OUTPUT.mkdir(parents=True, exist_ok=True)
    written = 0
    for index, seed in enumerate(SEEDS):
        role = DEFAULT_ROLES[index % len(DEFAULT_ROLES)]
        for arm in ARMS:
            path = OUTPUT / f"{arm}_s{seed}.yaml"
            path.write_text(TEMPLATE.format(arm=arm, role=role, seed=seed))
            written += 1
    counts: dict[str, int] = {}
    for index, _ in enumerate(SEEDS):
        role = DEFAULT_ROLES[index % len(DEFAULT_ROLES)]
        counts[role] = counts.get(role, 0) + 1
    print(f"wrote {written} configs to {OUTPUT}")
    print("treated-role balance across the 36 seeds:")
    for role, count in sorted(counts.items()):
        print(f"  {role}: {count}")


if __name__ == "__main__":
    main()
