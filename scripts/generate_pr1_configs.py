"""Generate the PR1-design experiment configs, one per arm and seed, so the arms cannot drift.

Every field except `seed` and `shock_type` must be byte-identical across all cells. Generating them
makes that checkable, and `tests/test_pr1_configs.py` asserts exactly one distinct body. A single
stray field such as `noise_sigma` would break the pairing by seed that the paired analysis needs.

The output is a pure function of this file and `affective_contagion.seeds`, so regenerating is
idempotent.
"""

from __future__ import annotations

from pathlib import Path

from affective_contagion.seeds import GENERATED_SEEDS

#: The PR1/PR3, PR7 and PR8 seed blocks, defined in the package so this generator and its test
#: share one source of truth.
SEEDS = GENERATED_SEEDS
ARMS = ("neutral", "affective")

TEMPLATE = """# PR1 cell: {arm} arm, seed {seed}. Generated by scripts/generate_pr1_configs.py.
# Do not hand-edit. Every field except `seed` and `shock_type` must be identical across all cells,
# so that their equality can be checked mechanically.
roles:
  - sentiment_analyst
  - fundamental_analyst
  - bull_researcher
  - bear_researcher
  - trader
  - risk_manager
topology: full
n_rounds: 7
shock_round: 4
shock_duration: 1
treated_role: sentiment_analyst
shock_type: {arm}
message_intervention: identity
fundamental_value: 100.0
price_impact: 0.02
mean_reversion: 0.01
noise_sigma: 0.003
seed: {seed}
var_maxlags: 3
irf_horizon: 10
"""


def main() -> None:
    """Write every PR1 cell, overwriting any previous generation."""
    destination = Path("configs/experiments/pr1")
    destination.mkdir(parents=True, exist_ok=True)
    written = 0
    for arm in ARMS:
        for seed in SEEDS:
            path = destination / f"{arm}_s{seed}.yaml"
            path.write_text(TEMPLATE.format(arm=arm, seed=seed), encoding="utf-8")
            written += 1
    print(f"wrote {written} PR1 cells to {destination}")


if __name__ == "__main__":
    main()
